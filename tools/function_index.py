#!/usr/bin/env python3
"""Build a readable index of the recompiled program's functions.

  python3 tools/function_index.py prg.bin data/analysis_bloodbro.json data/symbols_bloodbro.txt [out.txt]

For each function (call target / vector) it lists size, who calls it, what it calls and which
named hardware registers and game variables it touches (from data/symbols_bloodbro.txt), plus a
short hint about its role. This is a map for reading the code, not a decompilation.
Requires: pip install capstone
"""
import bisect
import collections
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from analyze_trace import make_decoder  # noqa: E402

ABS = re.compile(r"(?<![#\w])\$([0-9a-f]+)\.[wl]")


def load_symbols(path):
    syms = []  # (addr, size, name, desc)
    for line in open(path):
        if line[:1].isspace():  # continuation of the previous description
            continue
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        p = line.split(None, 3)
        syms.append((int(p[0], 16), int(p[1], 0), p[2], p[3] if len(p) > 3 else ""))
    syms.sort()
    return syms


def lookup(syms, starts, addr):
    k = bisect.bisect_right(starts, addr) - 1
    if k < 0:
        return None
    a, size, name, _ = syms[k]
    if addr == a or (size and addr < a + size):
        return name if addr == a else f"{name}+{addr - a:#x}"
    return None


HINTS = [
    ("HW_IN0", "reads player inputs"), ("HW_IN1", "reads start/service"), ("HW_DSW", "reads DIP switches"),
    ("SEIBU_", "talks to the sound CPU"), ("CRTC_", "sets video registers"),
    ("SPRITE_RAM", "writes sprites"), ("PALETTE_RAM", "palette"), ("TX_VRAM", "text layer"),
    ("BG_VRAM", "background tiles"), ("FG_VRAM", "foreground tiles"),
    ("P1_", "player 1 state"), ("P2_", "player 2 state"), ("G_STAGE_INDEX", "stage"),
    ("G_P1_ENERGY", "player energy"), ("G_CREDITS", "credits"), ("G_TOP_SCORE", "high score"),
]


def main():
    prg_path, ana_path, sym_path = sys.argv[1:4]
    out_path = sys.argv[4] if len(sys.argv) > 4 else None
    prg = open(prg_path, "rb").read()
    ana = json.load(open(ana_path))
    syms = load_symbols(sym_path)
    starts = [s[0] for s in syms]
    decode = make_decoder(prg)
    dec = lambda a: decode(a)  # noqa: E731

    funcs = sorted(set(ana["functions"]))
    fset = set(funcs)
    code = set(ana["executed"]) | set(ana["static_only"])

    info = {}
    callers = collections.defaultdict(set)
    for f in funcs:
        seen, work = set(), [f]
        callees, refs = set(), collections.Counter()
        while work and len(seen) < 6000:
            a = work.pop()
            while a not in seen and a in code:
                i = dec(a)
                if i is None:
                    break
                seen.add(a)
                text = f"{i.text}"
                for m in ABS.finditer(text):
                    nm = lookup(syms, starts, int(m.group(1), 16))
                    if nm:
                        refs[nm.split("+")[0]] += 1
                if i.kind == "call" and i.target is not None:
                    callees.add(i.target)
                    callers[i.target].add(f)
                elif i.kind in ("branch", "dbcc") and i.target is not None:
                    work.append(i.target)
                elif i.kind == "jump" and i.target is not None:
                    if i.target in fset and i.target != f:
                        callees.add(i.target)
                    else:
                        work.append(i.target)
                    break
                if i.kind in ("ret", "rte", "jump_ind", "jump"):
                    break
                a = i.end
        size = sum(dec(a).size for a in seen if dec(a))
        info[f] = dict(n=len(seen), size=size, callees=sorted(callees), refs=refs)

    lines = ["# Function index (generated by tools/function_index.py)",
             "# addr    insns bytes  callers  name / hints / touches", ""]
    for f in funcs:
        d = info[f]
        name = lookup(syms, starts, f)
        hints = []
        for key, text in HINTS:
            if any(r.startswith(key) for r in d["refs"]) and text not in hints:
                hints.append(text)
        touches = ", ".join(f"{k}x{v}" if v > 1 else k for k, v in sorted(d["refs"].items()))
        callee_s = ", ".join(f"{c:#x}" for c in d["callees"][:8]) + (" ..." if len(d["callees"]) > 8 else "")
        head = f"{f:#08x} {d['n']:5d} {d['size']:5d}  {len(callers[f]):3d}  " + (f"[{name}] " if name else "")
        lines.append(head + ("; ".join(hints)))
        if touches:
            lines.append(f"            touches: {touches}")
        if callee_s:
            lines.append(f"            calls:   {callee_s}")
    text = "\n".join(lines) + "\n"
    if out_path:
        open(out_path, "w").write(text)
        print(f"{len(funcs)} functions -> {out_path}")
    else:
        print(text)


if __name__ == "__main__":
    main()
