#!/usr/bin/env python3
"""Turns a MAME cheat file (bloodbro.xml) into src/cheats_builtin.inc, so the cheats are part of bloodbro.exe.

  python3 tools/embed_cheats.py data/bloodbro_cheats.xml src/cheats_builtin.inc
  python3 tools/embed_cheats.py --empty src/cheats_builtin.inc        (no built-in cheats)

Run it again and rebuild whenever the cheat list changes. A bloodbro.xml next to the program (or --cheat-file)
still takes precedence over the built-in list, which makes it easy to try changes without rebuilding.
"""
import sys

CHUNK = 12000  # characters per string piece (keeps every literal short for all compilers)


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--empty":
        src, out = None, sys.argv[2]
    elif len(sys.argv) == 3:
        src, out = sys.argv[1], sys.argv[2]
    else:
        sys.exit(__doc__)
    text = open(src, "rb").read().decode("utf-8").replace("\r\n", "\n") if src else ""
    delim = "BBCHEAT"
    assert (")" + delim + '"') not in text, "choose another raw string delimiter"
    lines = text.splitlines(keepends=True)
    chunks, cur = [], ""
    for ln in lines:
        if len(cur) + len(ln) > CHUNK and cur:
            chunks.append(cur)
            cur = ""
        cur += ln
    if cur:
        chunks.append(cur)
    with open(out, "w", newline="\n") as f:
        f.write("// Generated by tools/embed_cheats.py - do not edit.\n")
        f.write("// Cheat list in the MAME cheat file format, built into the program (source: %s).\n" % (src or "none"))
        f.write("static const char* const kBuiltinCheatChunks[] = {\n")
        for ch in chunks:
            f.write('    R"%s(%s)%s",\n' % (delim, ch, delim))
        f.write("    nullptr};\n")
    print(f"{len(text)} bytes in {len(chunks)} piece(s) -> {out}")


if __name__ == "__main__":
    main()
